// Refresh the art-only contact sheet after selecting another #145 output.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const game = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = 'design/source-assets/4-caricatures/production-145-2026-10-13';
const inventory = JSON.parse(await fs.readFile(path.join(game, sourceDir, 'inventory.json'), 'utf8'));
const records = [...inventory.portraits, ...inventory.motifs, inventory.axiomMotif]
    .filter(record => record?.status === 'selected')
    .map(record => ({
        id: record.id,
        name: record.persona || (record.id === 'art/axiom-rule-motif' ? 'Shared Axiom motif' : record.id.split('/').pop().replace('spell-motif-', '') + ' spell motif'),
        kind: record.species ? 'portrait' : 'motif',
        colour: record.colour || 'generic',
        rarity: record.rarity || null,
        pose: record.poseDirection || (record.species ? 'Original selected pose' : 'Magical object / scene'),
        contract: record.mechanicalContract || null,
        coverage: record.coverage || '',
        source: sourceDir + '/' + record.source,
        group: record.group || null,
    }));
if (new Set(records.map(record => record.id)).size !== records.length) throw new Error('Duplicate selected art id');
const data = JSON.stringify({issue: inventory.issue, date: inventory.date, records}, null, 2)
    .replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
await fs.writeFile(path.join(game, 'dev/art-production-data.js'),
    '// GENERATED by tools/prepare-art-preview-145.mjs. Art review only; no game registrations.\n'
    + "(function (root) {\n    'use strict';\n    root.Rift.devArtProduction = " + data + ';\n})(window);\n');
console.log('Contact sheet refreshed: ' + records.length + ' selected assets.');
