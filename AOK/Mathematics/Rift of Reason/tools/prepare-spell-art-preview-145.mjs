// Freeze a developer-only spell/Axiom art study; never register runtime cards or grants.
import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const game = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFile(path.join(game, file), 'utf8');
const catalogue = JSON.parse(await read('design/drafts/card-arena-2026-10-12/card-catalogue.json'));
const mapping = JSON.parse(await read('design/source-assets/4-caricatures/production-145-2026-10-13/proposed-card-art-mapping.json'));
const manifest = await read('data/assets.js'), context = {window: {Rift: {data: {}}}};
vm.runInNewContext(manifest, context);
const proposed = catalogue.cards.filter(card => card.kind === 'spell' || card.kind === 'axiom');
const byId = new Map(mapping.rows.map(row => [row.cardId, row]));
if (byId.size !== mapping.rows.length || proposed.length !== byId.size) throw new Error('Expected exactly one art mapping per spell/Axiom');
const records = proposed.map(card => {
    const row = byId.get(card.id);
    if (!row || row.kind !== card.kind || row.affinity !== card.affinity || !context.window.Rift.data.assets[row.artId]) throw new Error('Invalid or unbuilt art mapping: ' + card.id);
    return {...card, artId: row.artId, bespoke: !!row.previousArtId};
});
const data = JSON.stringify({issue: 145, status: catalogue.status, records}, null, 2)
    .replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
const source = '// GENERATED by tools/prepare-spell-art-preview-145.mjs. Proposal art review only.\n'
    + "(function (root) {\n    'use strict';\n    root.Rift.devSpellArt = " + data + ';\n})(window);\n';
await fs.writeFile(path.join(game, 'dev/spell-art-data.js'), source);
const revision = createHash('sha256').update(manifest).update(source).digest('hex').slice(0, 12);
const html = await read('dev/spell-art.html');
await fs.writeFile(path.join(game, 'dev/spell-art.html'), html.replace(/((?:data\/assets|dev\/spell-art-data)\.js\?v=)[^" ]+/g, '$1spell-' + revision));
console.log('Spell art study: ' + records.filter(c => c.kind === 'spell').length + ' spells, ' + records.filter(c => c.kind === 'axiom').length + ' Axioms; ' + records.filter(c => c.bespoke).length + ' individual paintings. Version ' + revision + '.');
